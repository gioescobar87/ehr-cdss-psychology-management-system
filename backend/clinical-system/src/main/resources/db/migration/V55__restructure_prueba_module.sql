-- DROP CURRENT STRUCTURE

DROP TABLE interpretacion_prueba;
DROP TABLE resultado_prueba;
DROP TABLE prueba_psicologica;
DROP TABLE tipo_prueba;

-- CREATION OF ONE PRUEBA CATALOGO

CREATE TABLE prueba_psicologica
(
    id                      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre                  VARCHAR(200) NOT NULL,
    descripcion             TEXT,
    objetivo_prueba         TEXT NOT NULL,
    instrucciones_aplicacion TEXT NOT NULL,
    consideraciones         TEXT,
    estado_id               INTEGER NOT NULL,

    CONSTRAINT pk_prueba_psicologica
        PRIMARY KEY (id),

    CONSTRAINT fk_prueba_psicologica_estado
        FOREIGN KEY (estado_id)
        REFERENCES public.estado (id)
);

-- CREATION OF APPLICACION PRUEBA

CREATE TABLE public.aplicacion_prueba
(
    id                      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    sesion_id               INTEGER NOT NULL,
    prueba_psicologica_id   INTEGER NOT NULL,
    fecha_aplicacion        DATE NOT NULL,
    archivo_adjunto         TEXT,
    interpretacion          TEXT,
    estado_id               INTEGER NOT NULL,

    CONSTRAINT pk_aplicacion_prueba
        PRIMARY KEY (id),

    CONSTRAINT fk_aplicacion_prueba_sesion
        FOREIGN KEY (sesion_id)
        REFERENCES public.sesion (id),

    CONSTRAINT fk_aplicacion_prueba_prueba
        FOREIGN KEY (prueba_psicologica_id)
        REFERENCES public.prueba_psicologica (id),

    CONSTRAINT fk_aplicacion_prueba_estado
        FOREIGN KEY (estado_id)
        REFERENCES public.estado (id)
);