CREATE TABLE sesion_criterio_clinico (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sesion_id INTEGER NOT NULL,
    criterio_clinico_id INTEGER NOT NULL,
    presente BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT fk_sesion_criterio_clinico_sesion
        FOREIGN KEY (sesion_id)
        REFERENCES public.sesion (id),

    CONSTRAINT fk_sesion_criterio_clinico_criterio
        FOREIGN KEY (criterio_clinico_id)
        REFERENCES public.criterio_clinico (id)
);

CREATE INDEX idx_sesion_criterio_clinico_sesion
    ON public.sesion_criterio_clinico (sesion_id);

CREATE INDEX idx_sesion_criterio_clinico_criterio
    ON public.sesion_criterio_clinico (criterio_clinico_id);
