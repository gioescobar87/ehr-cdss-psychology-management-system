        FROM tmp_diagnostico_criterio t
        LEFT JOIN public.diagnostico d
            ON d.nombre = t.diagnostico_nombre
        WHERE d.id IS NULL
    ) x;

    IF missing_diagnosticos IS NOT NULL THEN
        RAISE EXCEPTION
            'Diagnósticos no encontrados en public.diagnostico:%',
            E'\n' || missing_diagnosticos;
    END IF;
END $$;


DO $$
DECLARE
    missing_criterios text;
BEGIN
    SELECT string_agg(
        x.criterio_nombre,
        E'\n' ORDER BY x.criterio_nombre
    )
    INTO missing_criterios
    FROM (
        SELECT DISTINCT t.criterio_nombre
        FROM tmp_diagnostico_criterio t
        LEFT JOIN public.criterio_clinico cc
            ON cc.nombre = t.criterio_nombre
        WHERE cc.id IS NULL
    ) x;

    IF missing_criterios IS NOT NULL THEN
        RAISE EXCEPTION
            'Criterios clínicos no encontrados en public.criterio_clinico:%',
            E'\n' || missing_criterios;
    END IF;
END $$;


INSERT INTO public.diagnostico_criterio_clinico (
    diagnostico_id,
    criterio_clinico_id
)
SELECT DISTINCT
    d.id,
    cc.id
FROM tmp_diagnostico_criterio t
JOIN public.diagnostico d
    ON d.nombre = t.diagnostico_nombre
JOIN public.criterio_clinico cc
    ON cc.nombre = t.criterio_nombre
ON CONFLICT (diagnostico_id, criterio_clinico_id) DO NOTHING;


